S_RECIPES: dict[str, dict[str, Any]] = {
    "S0": {"recipe_id": "S0", "operators": ("add", "sub", "mul"),
           "role": "short_polynomial_control"},
    "S1": {"recipe_id": "S1", "operators": ("add", "sub", "mul", "safe_ratio"),
           "role": "S0_plus_safe_ratio"},
    "S2": {"recipe_id": "S2", "operators": ("add", "sub", "mul", "tanh", "log1p_abs"),
           "role": "S0_plus_bounded_unary"},
    "S3": {"recipe_id": "S3",
           "operators": ("add", "sub", "mul", "safe_ratio", "tanh", "log1p_abs"),
           "role": "union_of_S1_and_S2"},
}

BINARY_OPERATORS = ("add", "sub", "mul", "safe_ratio")
UNARY_OPERATORS = ("tanh", "log1p_abs")

#: Pre-registered search budget.  ``eval_budget`` is an *upper* limit on
#: expression evaluations per training subset; the in-repo backend counts every
#: evaluation exactly and records the realised count and stop reason.
S_LIMITS: dict[str, Any] = {
    "max_nodes": 24,
    "max_depth": 5,
    "eval_budget": 200_000,
    "max_candidates": 12,
    "beam_width": 48,
    "no_improve_rounds": 4,
    "const_seeds": (0.5, 1.0, 2.0),
    "constant_refit_max_nfev": 400,
    "constant_bound": 100.0,
}


def s_recipe_spec(recipe_id: str) -> dict[str, Any]:
    key = str(recipe_id).upper()
    if key not in S_RECIPES:
        raise ValueError(f"Unknown S recipe: {recipe_id!r}")
    return deepcopy(S_RECIPES[key])


class SymbolicLimits:
    """Validated, explicit search budget; nothing is silently ignored."""

    def __init__(self, overrides: Mapping[str, Any] | None = None) -> None:
        unknown = sorted(set(overrides or {}) - set(S_LIMITS))
        if unknown:
            raise ValueError(f"Unknown S limit overrides: {unknown}")
        merged = dict(S_LIMITS)
        merged.update({str(k): v for k, v in (overrides or {}).items()})
        self.max_nodes = int(merged["max_nodes"])
        self.max_depth = int(merged["max_depth"])
        self.eval_budget = int(merged["eval_budget"])
        self.max_candidates = int(merged["max_candidates"])
        self.beam_width = int(merged["beam_width"])
        self.no_improve_rounds = int(merged["no_improve_rounds"])
        self.const_seeds = tuple(float(v) for v in merged["const_seeds"])
        self.constant_refit_max_nfev = int(merged["constant_refit_max_nfev"])
        self.constant_bound = float(merged["constant_bound"])
        if min(self.max_nodes, self.max_depth, self.eval_budget, self.max_candidates,
               self.beam_width, self.no_improve_rounds) <= 0:
            raise ValueError("Invalid S search limits")
        if self.max_nodes < 5:
            raise ValueError("S max_nodes must leave room for the affine head")

    def as_dict(self) -> dict[str, Any]:
        return {
            "max_nodes": int(self.max_nodes),
            "max_depth": int(self.max_depth),
            "eval_budget": int(self.eval_budget),
            "max_candidates": int(self.max_candidates),
            "beam_width": int(self.beam_width),
            "no_improve_rounds": int(self.no_improve_rounds),
            "const_seeds": list(self.const_seeds),
            "constant_refit_max_nfev": int(self.constant_refit_max_nfev),
            "constant_bound": float(self.constant_bound),
            "budget_kind": "exact_expression_evaluation_counter",
        }


class SymbolicSpec:
    def __init__(self, recipe_id: str) -> None:
        payload = s_recipe_spec(recipe_id)
        self.recipe_id = str(payload["recipe_id"])
        self.operators = tuple(str(v) for v in payload["operators"])
        self.role = str(payload["role"])
        for name in self.operators:
            if name not in {*BINARY_OPERATORS, *UNARY_OPERATORS}:
                raise ValueError(f"Unknown symbolic operator: {name!r}")

    def as_dict(self) -> dict[str, Any]:
        return {
            "recipe_id": self.recipe_id,
            "operators": list(self.operators),
            "role": self.role,
            "binary_operators": [n for n in self.operators if n in BINARY_OPERATORS],
            "unary_operators": [n for n in self.operators if n in UNARY_OPERATORS],
            "forbidden": ["bare_division", "power", "sin", "cos", "conditionals"],
        }


