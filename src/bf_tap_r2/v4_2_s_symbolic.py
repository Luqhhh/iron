"""V4.2 S line: constrained symbolic regression over short expressions.

Evidence basis: the PySR documentation (https://pysr.ai/v1.5.9/options), which
supports configurable operators, complexity/depth constraints, custom losses and
NumPy export.

This round does **not** assume that the real data was generated by a
recoverable formula.  The only hypothesis under test is whether a constrained
short nonlinear expression can learn a more effective combination of the
current inputs than the existing models.  Nothing here is described as a real
blast-furnace mechanism or as recovery of an official generator.

Two backends exist:

* the in-repo bounded AST search, whose evaluation counter is exact and whose
  per-training-subset cap is enforced and recorded;
* an optional PySR adapter that is only used when the installed backend is
  verified to accept and report an exact evaluation budget.

Operator sets (per target):

===== ====================================================
ID    operator set
===== ====================================================
S0    ``+``, ``-``, ``*``  (short polynomial control)
S1    S0 + ``safe_ratio(a, b) = a / (1 + b * b)``
S2    S0 + ``tanh(a)``, ``log1p(abs(a))``
S3    union of S1 and S2
===== ====================================================

Constraints: at most 24 nodes and depth 5; nonlinear unary operators may not
self-nest; ``safe_ratio`` may not self-nest.  There is no arbitrary exponent,
no bare division, no ``sin``/``cos`` and no large conditional branch.
"""
